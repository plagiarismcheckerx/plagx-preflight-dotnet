// Generates src/Plagx.Preflight/UnicodeData.cs from the JavaScript engine so the
// .NET port matches the JavaScript reference exactly:
//  - \p{L}, \p{M}, \p{Lu}, \p{Ll} as .NET regex fragments, including characters
//    outside the BMP (which .NET's own \p{..} cannot match as one character);
//  - toUpperCase / toLowerCase mappings that differ from "unchanged".
// Usage: node scripts/build-unicode.mjs
import { writeFileSync } from 'node:fs';

const u = (n) => `\\u${n.toString(16).toUpperCase().padStart(4, '0')}`;

function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp += 1) {
    const hit = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  return out;
}

/** BMP part as character-class content, astral part as an alternation of surrogate pairs. */
function fragments(re) {
  const bmp = [];
  const astral = [];
  for (const [a, b] of ranges(re)) {
    if (b <= 0xffff) { bmp.push([a, b]); continue; }
    if (a <= 0xffff) { bmp.push([a, 0xffff]); }
    let lo = Math.max(a, 0x10000);
    while (lo <= b) {
      const hi = ((lo - 0x10000) >> 10) + 0xd800;
      const blockEnd = Math.min(b, 0x10000 + ((hi - 0xd800 + 1) << 10) - 1);
      const l1 = ((lo - 0x10000) & 0x3ff) + 0xdc00;
      const l2 = ((blockEnd - 0x10000) & 0x3ff) + 0xdc00;
      astral.push(`${u(hi)}${l1 === l2 ? u(l1) : `[${u(l1)}-${u(l2)}]`}`);
      lo = blockEnd + 1;
    }
  }
  const cls = bmp.map(([a, b]) => (a === b ? u(a) : `${u(a)}-${u(b)}`)).join('');
  return { cls, astral: astral.join('|') };
}

function caseMap(fn) {
  const out = [];
  for (let cp = 0; cp < 0x110000; cp += 1) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const s = String.fromCodePoint(cp);
    const m = fn(s);
    if (m !== s) out.push(`{ 0x${cp.toString(16).toUpperCase()}, "${[...m].map((c) => {
      const n = c.codePointAt(0);
      return n > 0xffff ? `\\U${n.toString(16).toUpperCase().padStart(8, '0')}` : u(n);
    }).join('')}" }`);
  }
  return out;
}

const chunk = (s, n = 110) => s.match(new RegExp(`.{1,${n}}(?=\\\\u|\\||$)`, 'g')).map((l) => `        "${l}"`).join(' +\n');
let cs = `// <auto-generated>
// Generated by scripts/build-unicode.mjs from the JavaScript engine (Node ${process.versions.node},
// Unicode ${process.versions.unicode}) so results match the JavaScript reference. Do not edit.
// </auto-generated>
namespace Plagx.Preflight;

internal static class UnicodeData
{
`;
for (const [name, re] of Object.entries({ L: /\p{L}/u, M: /\p{M}/u, Lu: /\p{Lu}/u, Ll: /\p{Ll}/u })) {
  const f = fragments(re);
  cs += `    /// <summary>BMP part of \\p{${name}} (character-class content).</summary>\n    public const string ${name}Bmp =\n${chunk(f.cls)};\n\n`;
  cs += `    /// <summary>Non-BMP part of \\p{${name}} as an alternation of surrogate pairs.</summary>\n    public const string ${name}Astral =\n${chunk(f.astral)};\n\n`;
}
cs += `    /// <summary>String.prototype.toUpperCase for every code point it changes.</summary>\n    public static readonly Dictionary<int, string> Upper = new()\n    {\n        ${caseMap((s) => s.toUpperCase()).join(',\n        ')},\n    };\n\n`;
cs += `    /// <summary>String.prototype.toLowerCase for every code point it changes (context-free).</summary>\n    public static readonly Dictionary<int, string> Lower = new()\n    {\n        ${caseMap((s) => s.toLowerCase()).join(',\n        ')},\n    };\n}\n`;
writeFileSync(new URL('../src/Plagx.Preflight/UnicodeData.cs', import.meta.url), cs);
console.log('Wrote src/Plagx.Preflight/UnicodeData.cs');
